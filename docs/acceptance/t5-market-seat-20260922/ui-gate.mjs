import { spawn } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
const [,,rootUrl,scratch]=process.argv;
const binary='/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const profile=join(scratch,'chrome-profile');
const child=spawn(binary,['--headless=new','--no-first-run','--no-default-browser-check','--disable-dev-shm-usage','--remote-debugging-address=127.0.0.1','--remote-debugging-port=0',`--user-data-dir=${profile}`,'about:blank'],{detached:true,stdio:['ignore','ignore','pipe']});
let stderr='';child.stderr.on('data',b=>{stderr=(stderr+b).slice(-4000);});
const until=async(fn,ms=20000)=>{const end=Date.now()+ms;for(;;){try{const v=await fn();if(v)return v;}catch{}if(Date.now()>end)throw new Error('timeout: '+stderr.slice(-400));await new Promise(r=>setTimeout(r,250));}};
const port=await until(async()=>{const t=await readFile(join(profile,'DevToolsActivePort'),'utf8');return t.trim().split('\n');});
const socket=new WebSocket(`ws://127.0.0.1:${port[0]}${port[1]}`);
await new Promise((res,rej)=>{socket.addEventListener('open',res,{once:true});socket.addEventListener('error',rej,{once:true});});
let id=0;const pending=new Map();
socket.addEventListener('message',e=>{const m=JSON.parse(e.data);const r=pending.get(m.id);if(!r)return;pending.delete(m.id);clearTimeout(r.timer);m.error?r.reject(new Error(JSON.stringify(m.error))):r.resolve(m.result);});
const send=(method,params={},sessionId)=>new Promise((resolve,reject)=>{const rid=++id;const timer=setTimeout(()=>{pending.delete(rid);reject(new Error('CDP timeout '+method));},30000);pending.set(rid,{resolve,reject,timer});socket.send(JSON.stringify({id:rid,method,params,...(sessionId?{sessionId}:{})}));});
const{targetId}=await send('Target.createTarget',{url:'about:blank'});
const{sessionId}=await send('Target.attachToTarget',{targetId,flatten:true});
const call=(m,p)=>send(m,p,sessionId);
await call('Page.enable');await call('Runtime.enable');await call('Log.enable');
const logs=[];
socket.addEventListener('message',e=>{const m=JSON.parse(e.data);
  if(m.method==='Runtime.consoleAPICalled')logs.push({kind:m.params.type,text:m.params.args.map(a=>a.value??a.description??'').join(' ')});
  if(m.method==='Log.entryAdded')logs.push({kind:'log:'+m.params.entry.level,text:m.params.entry.text});
  if(m.method==='Runtime.exceptionThrown')logs.push({kind:'exception',text:m.params.exceptionDetails.exception?.description??m.params.exceptionDetails.text});});
const ev=async expr=>{const r=await call('Runtime.evaluate',{expression:expr,awaitPromise:true,returnByValue:true});if(r.exceptionDetails)throw new Error(JSON.stringify(r.exceptionDetails).slice(0,800));return r.result.value;};
await call('Page.navigate',{url:rootUrl});
await until(()=>ev(`document.readyState==='complete'`));
await new Promise(r=>setTimeout(r,6000));
const report={};
report.marketButton=await ev(`[...document.querySelectorAll('button')].filter(b=>b.textContent.trim()==='市场').length`);
report.marketSeatRegistered=await ev(`(()=>{try{const roots=[...document.querySelectorAll('*')];return null;}catch(e){return String(e)}})()`);
await ev(`(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent.trim()==='市场');if(b)b.click();return !!b;})()`);
await new Promise(r=>setTimeout(r,5000));
report.overlayTitle=await ev(`document.querySelector('.hm-market h1')?.textContent ?? null`);
report.conflictNotice=await ev(`document.querySelector('[data-hanamesh-market-conflict]')?.textContent ?? null`);
report.cards=await ev(`document.querySelectorAll('[data-hanamesh-library-item]').length`);
report.filters=await ev(`[...document.querySelectorAll('.hm-library-toolbar option')].map(o=>o.textContent)`);
report.installedRows=await ev(`[...document.querySelectorAll('[data-hanamesh-installed]')].map(n=>n.textContent)`);
report.restartNotice=await ev(`document.querySelector('[data-hanamesh-restart]')?.textContent ?? null`);
report.errors=logs.filter(l=>/error|exception/i.test(l.kind)||/hanamesh-app-host market/.test(l.text));
report.allLogs=logs.slice(-40);
await writeFile(join(scratch,'evidence','ui-gate-2-dshmarket.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify({marketButton:report.marketButton,overlayTitle:report.overlayTitle,conflictNotice:report.conflictNotice,cards:report.cards,filters:report.filters,installedRows:report.installedRows,restartNotice:report.restartNotice,errorCount:report.errors.length},null,2));
try{process.kill(-child.pid,'SIGKILL');}catch{}
socket.close();process.exit(0);
